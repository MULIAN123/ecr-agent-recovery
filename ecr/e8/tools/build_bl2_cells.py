"""Build the bl2 unit table: fairness arm CA-LOG + held-out validation, all arms in one batch.

Scenarios
  dev (64)      : the frozen 2b scenarios (52 historical + 12 F7), scenario/truth/contract byte-for-byte from
                  private/cells_p3.json (FULL / v1 units). Groups 'hist' and 'F7'.
  heldout (92)  : generated by a fixed grammar, never run by any arm before:
                  overlays   F2_FOREIGN_ACCEPT, F3_WEAK_ACK, F4_REORDERED_CALLBACK, F6_LOST_DISPATCH_FAILURE,
                             F7_LOCAL_FAILURE_AFTER_DISPATCH  (every runner overlay except F5, see below)
                  x barriers B2_DROP, B2_ARRIVE, B2_LATE, B3_LATE, B4, B5  (every barrier after dispatch whose
                             journal has a dispatch record and no persisted outcome, so every overlay applies)
                  x profiles P0-P3
                  minus the 7 overlay/barrier pairs of the dev set (F2/F3/F7 at B2_DROP, F4/F6 at B5,
                  F7 at B3_LATE and B4)  ->  23 pairs x 4 = 92 scenarios. Group 'heldout'.
                  Truth rule (fixed before any run): the truth row of the same barrier and profile in the dev
                  table (dispatched, original_request_effect, max_allowed_effects 1, send_permitted, and
                  safe_opportunity = profile != P0), with scenario_id, overlay and note replaced. The overlays
                  only change local records; the external effect is decided by the barrier and the profile.
                  F5 (superseded task version) is excluded: after dispatch the scorer's truth fields cannot
                  express which version an effect belongs to, so no truth row could be written without a
                  scorer change.
Arms (fixed before any run)
  ECR-G R2A  classifier FULL, executor v2, mode R2A      ECR-G R2B  FULL, v2, R2B
  CONV       reference policy, executor CONV             INTENT-LOG / RIFL-C / CA-LOG  executor BL2
Family VX: 156 scenarios x 6 arms = 936 units. Family VQ: 8 runner-qualification units (not results).
Usage: python -I build_bl2_cells.py <cells_p3.json> <out cells_bl2.json>
"""
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "runner"))
from p3lib import attempt_dirname, attempt_id, unit_id  # noqa: E402

CELLS_P3_SHA256 = "c244199721f4982bbda5aacf2b09e837e19a6b1395ab62a6dcdbc7025aa190b6"
OVERLAYS = ("F2_FOREIGN_ACCEPT", "F3_WEAK_ACK", "F4_REORDERED_CALLBACK", "F6_LOST_DISPATCH_FAILURE",
            "F7_LOCAL_FAILURE_AFTER_DISPATCH")
SHORT = {"F2_FOREIGN_ACCEPT": "F2", "F3_WEAK_ACK": "F3", "F4_REORDERED_CALLBACK": "F4",
         "F6_LOST_DISPATCH_FAILURE": "F6", "F7_LOCAL_FAILURE_AFTER_DISPATCH": "F7"}
BARRIERS = ("B2_DROP", "B2_ARRIVE", "B2_LATE", "B3_LATE", "B4", "B5")
PROFILES = ("P0", "P1", "P2", "P3")
ARMS = (  # label, classifier slot, executor, mode, policy
    ("ECR-G R2A", "FULL", "v2", "R2A", "EBRQ2"),
    ("ECR-G R2B", "FULL", "v2", "R2B", "EBRQ2"),
    ("CONV", "-", "CONV", None, "CONV"),
    ("INTENT-LOG", "INTENT_LOG", "BL2", None, "INTENT_LOG"),
    ("RIFL-C", "RIFL_C", "BL2", None, "RIFL_C"),
    ("CA-LOG", "CA_LOG", "BL2", None, "CA_LOG"),
)
QUAL = (  # scenario_id, arm label: CA-LOG fence/idempotent/P0 paths, held-out paths of ECR-G and CONV
    ("B2_DROP_P1", "CA-LOG"), ("B4_P2", "CA-LOG"), ("F6_LOST_DISPATCH_FAILURE_P0", "CA-LOG"),
    ("H_F4_B2_DROP_P3", "CA-LOG"), ("H_F2_B4_P1", "ECR-G R2A"), ("H_F6_B2_DROP_P2", "ECR-G R2B"),
    ("H_F3_B2_LATE_P0", "CONV"), ("H_F7_B5_P3", "RIFL-C"),
)


def ids(name: str) -> dict:
    return {"identity": {"artifactId": f"{name}-artifact", "artifactSetId": f"{name}-set", "attemptId": f"{name}-a1",
                         "bindingGeneration": 1, "deliverableId": f"{name}-deliverable", "queueBindingId": f"{name}-binding",
                         "taskId": f"{name}-task", "taskStateVersion": 1},
            "logical_operation_id": f"{name}-op", "queue_item_id": f"{name}-queue", "transport_request_id": f"{name}-t1"}


def main():
    src = Path(sys.argv[1])
    digest = hashlib.sha256(src.read_bytes()).hexdigest()
    if digest != CELLS_P3_SHA256:
        raise SystemExit(f"source table is not the frozen 2b cells_p3.json: {digest}")
    p3 = json.loads(src.read_text())
    dev = {}
    for u in p3["units"]:
        if u["family"] == "P3A" and u["classifier_arm"] == "FULL" and u["executor"] == "v1":
            dev[u["scenario"]["scenario_id"]] = u
    assert len(dev) == 64
    dev_pairs = {(u["scenario"].get("overlay"), u["scenario"]["barrier"]) for u in dev.values() if u["scenario"].get("overlay")}
    base = {(u["scenario"]["barrier"], u["scenario"]["profile"]): u for u in dev.values() if not u["scenario"].get("overlay")}
    scen = []  # (scenario, truth, contract, group)
    for sid in sorted(dev):
        u = dev[sid]
        scen.append((u["scenario"], u["truth"], u["endpoint_contract"], u["group"]))
    held = 0
    for ov in OVERLAYS:
        for b in BARRIERS:
            if (ov, b) in dev_pairs:
                continue
            for p in PROFILES:
                bu = base[(b, p)]
                sid = f"H_{SHORT[ov]}_{b}_{p}"
                truth = {**bu["truth"], "scenario_id": sid, "overlay": ov,
                         "note": f"held-out: {ov} applied after a kill at {b}; external truth of base {b}/{p}"}
                scen.append(({"barrier": b, "overlay": ov, "profile": p, "scenario_id": sid}, truth,
                             bu["endpoint_contract"], "heldout"))
                held += 1
    in_grammar = {(o, b) for o, b in dev_pairs if o in OVERLAYS and b in BARRIERS}
    assert len(dev_pairs) == 8 and len(in_grammar) == 7 and held == 92, (sorted(dev_pairs), held)  # 8th dev pair: F5 at B1
    units, counters = [], {"VX": 0, "VQ": 0}

    def add(family, sc, tr, contract, group, arm, extra):
        label, clf, ex, mode, policy = arm
        counters[family] += 1
        name = f"{family}-{counters[family]:04d}"
        uid = unit_id(family, sc["scenario_id"], clf, ex, mode)
        attempt_dirname(attempt_id(uid, 1))
        units.append({"unit_id": uid, "name": name, "family": family, "arm_label": label, "scenario": sc, "truth": tr,
                      "classifier_arm": "FULL" if clf == "FULL" else "-", "executor": ex, "r2_mode": mode,
                      "policy": policy, "endpoint_contract": contract, "ids": ids(name), "group": group, **extra})

    for sc, tr, contract, group in scen:
        for arm in ARMS:
            exposure = ("HELD-OUT: scenario generated by the frozen grammar, never run before" if group == "heldout"
                        else "DEV: scenario and truth seen in 2b")
            add("VX", sc, tr, contract, group, arm, {"exposure": exposure})
    by_sid = {s[0]["scenario_id"]: s for s in scen}
    arm_of = {a[0]: a for a in ARMS}
    for sid, label in QUAL:
        sc, tr, contract, group = by_sid[sid]
        add("VQ", sc, tr, contract, group, arm_of[label], {"exposure": "QUALIFICATION (not an experiment result)"})
    uids = [u["unit_id"] for u in units]
    assert len(uids) == len(set(uids))
    vx = [u for u in units if u["family"] == "VX"]
    assert len(vx) == 936
    summary = {"VX_units": len(vx), "VQ_units": len(units) - len(vx), "heldout_scenarios": held,
               "dev_pairs_excluded": sorted(map(list, dev_pairs)), "by_arm_group": {}}
    for u in vx:
        k = f"{u['arm_label']}|{u['group']}"
        summary["by_arm_group"][k] = summary["by_arm_group"].get(k, 0) + 1
    out = {"status": "CANDIDATE bl2 - frozen only by the bl2 freeze record", "source_cells_p3_sha256": digest,
           "summary": summary, "qualification_unit_ids": [u["unit_id"] for u in units if u["family"] == "VQ"],
           "units": units}
    Path(sys.argv[2]).write_text(json.dumps(out, indent=1), encoding="utf-8")
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
