"""Write execution-manifest-e8.json (derived from make_execution_manifest_bl6.py: same guard fields; candidate binding is
to the E8 freeze record instead of a code manifest). Run on the guest after arms_js was generated by the pinned Node.
Never overwrites. Excluded from "files": the manifest itself, qualification-authorization-e8.json, __pycache__, *.pyc.
The manifest contains no per-deployment timestamp (bl6 Erratum D2-E1 lesson): strip-manifest.json is listed by hash
like any other file, and equivalence across deployments is checked by tools/verify_exec_manifest.py --compare.
Usage: python3 -I make_execution_manifest_e8.py --pkg DIR --freeze-record FREEZE_RECORD_E8.json --vm-uuid U [...]
           --python-version X.Y.Z --kernel RELEASE --node-sha256 HEX --route J
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

NAME = "execution-manifest-e8.json"
EXCLUDE = {NAME, "qualification-authorization-e8.json"}
PUBLIC_PREFIXES = ("src/", "src_c1/", "src_e1/", "arms/", "arms_js/")
PUBLIC_TOOLS = ("tools/planner_recorder.py", "tools/replay.py", "tools/e8_diag.py", "tools/w6_order.py", "tools/seed_effect.py")


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pkg", required=True); ap.add_argument("--freeze-record", required=True)
    ap.add_argument("--vm-uuid", action="append", required=True); ap.add_argument("--python-version", required=True)
    ap.add_argument("--kernel", required=True); ap.add_argument("--node-sha256", required=True); ap.add_argument("--route", choices=["J"], required=True)
    a = ap.parse_args()
    pkg = Path(a.pkg).resolve()
    out = pkg / NAME
    if out.exists():
        print("refusing to overwrite", out); return 2
    files = {}
    for p in sorted(pkg.rglob("*")):
        rel = p.relative_to(pkg).as_posix()
        if p.is_dir() or rel in EXCLUDE or "__pycache__" in rel or rel.endswith(".pyc"):
            continue
        if p.is_symlink():
            print("symlink in package", rel); return 2
        files[rel] = sha(p)
    strip = json.loads((pkg / "arms_js/strip-manifest.json").read_text())
    if strip.get("status") != "COMPLETED" or strip.get("node_binary_sha256") != a.node_sha256:
        print("arms_js not generated by the pinned Node"); return 2
    freeze = json.loads(Path(a.freeze_record).read_text())
    problems = [f"{rel} differs from freeze record" for rel, d in freeze["package_files"].items() if files.get(rel) != d]
    problems += [f"{rel} not in freeze record" for rel in files if rel not in freeze["package_files"] and not rel.startswith("arms_js/")]
    if problems:
        print("\n".join(problems)); return 2
    public = [rel for rel in files if rel.startswith(PUBLIC_PREFIXES) or rel in PUBLIC_TOOLS]
    manifest = {"status": "EXECUTION_MANIFEST_E8", "vm_uuids": [u.lower() for u in a.vm_uuid], "python_version": a.python_version,
                "kernel": a.kernel, "node_binary_sha256": a.node_sha256, "planner_route": a.route,
                "freeze_record_sha256": sha(Path(a.freeze_record)), "files": files, "public_files": sorted(public)}
    out.write_text(json.dumps(manifest, indent=1, sort_keys=True) + "\n")
    print(json.dumps({"written": str(out), "sha256": sha(out), "files": len(files), "public": len(public)}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
